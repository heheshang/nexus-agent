//! nexus-workflow —— **图引擎**。
//!
//! # 本 crate 负责什么
//!
//! | 关注点 | 模块 |
//! |---|---|
//! | **冻结定义**（规范化 + 哈希 + 引擎版本） | [`definition`] |
//! | **图编译**（拓扑排序 + 入度 + 环检测 + 递归检测 + 展开上限） | [`graph`] |
//! | **节点执行契约**（`NodeInvoke` / `NodeError` 三分类 / 并发闸门） | [`node`] |
//! | **图状态**（键 → JSON 值 + 4 MiB 上限） | [`state`] |
//! | **条件求值**（`evalexpr` 布尔求值） | [`condition`] |
//! | **模板渲染**（`render_args` 工具参数渲染） | [`template`] |
//!
//! # 本 crate **不**负责什么
//!
//! | 不负责 | 归属 |
//! |---|---|
//! | **持久化**（定义落库、run 记录、租约、fencing、幂等） | `nexus-repo` / `nexus-execution`（NEX-37 / NEX-41 ~ NEX-45） |
//! | **中断提案**（人工审批的挂起与恢复） | NEX-40 |
//! | **执行 driver**（领取、版本三元组校验、事件发射） | NEX-41 |
//! | **具体的工具 / LLM 节点实现** | P8 / P3 —— P6 只交付**注入的** trait |
//! | **DSL 文本前端** | 决策 D15（OQ-2）—— 登记为 F4 |
//!
//! # 为什么「图引擎」与「持久化」要**分开**
//!
//! 图编译是**纯内存计算** —— 输入一份 JSON，输出一个不可变的图结构。
//! 它**不碰数据库**，因此**不需要** `sqlx`，**不依赖** `nexus-repo`。
//!
//! 这条边界是**依赖方向**的硬约束：
//! `nexus-workflow` 是**能力层**，`nexus-repo` 是**数据层**，
//! 能力层**不得**反向依赖数据层（架构文档 §4.1.2）。
//!
//! 持久化的那一侧（`nexus-execution`）**依赖** `nexus-workflow` ——
//! 方向是单向的。
//!
//! # 为什么冻结定义要**复用** `nexus_core::canonical`
//!
//! 规范化规则是**已定稿**的（架构文档 §2.5.3），而 `nexus-core` 里已有
//! **实测过**的实现。自己再写一份 = 两份规范化 = **哈希漂移**的入口。
//!
//! `nexus-workflow` 与 `nexus-execution` **互相不能依赖**（否则成环）——
//! 所以这份实现**必须**在 `nexus-core`（依赖图的根）里。
//!
//! # 为什么节点错误是**三分类** enum
//!
//! 架构文档 §2.6.2：领域错误是 enum，不是字符串。
//! `Retryable` / `Permanent` / `Interrupt` 的**处置完全不同**
//! —— 重试 / 结束 / 挂起。
//!
//! 把三者合成一个字符串 = 「到底该不该重试」变成**运行时猜** ——
//! 而猜错在支付类工具上就是**重复扣费**。
//!
//! # 参见
//!
//! - 架构文档 §2.5.2 / §2.5.3 —— 冻结定义与规范化
//! - 架构文档 §2.6.2 —— 领域错误是 enum
//! - 架构文档 §2.3.2 / §2.3.3 —— 泛型优先，`dyn` 兜底
//! - 参考架构 §3.5.1 / §3.5.2 —— 图编译与展开上限
//! - 参考架构 §3.5.4 —— `render_args` 模板求值
//! - Spec 层 §3.1 / §3.2 / §3.3 / §3.4 / §3.5 —— P6 的全部核心契约

